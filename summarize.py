"""Rebuild the results tables (results/SUMMARY.md) and charts (figures/) from the raw result files. No API calls.

Stale = an answer to a changed-policy question that states the v1 value ("30 days", "$6.95", "7 days") when graded against v2.
That check is exact string matching, so it is the most reliable number here. Scores use the keyword grader; the
judge-adjusted score swaps in the LLM judge's verdict wherever it ran (all keyword failures, 20% of passes).
Usage: python summarize.py
"""
import glob, json, re
from pathlib import Path
from statistics import mean

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).parent
QS = {json.loads(l)["id"]: json.loads(l) for l in open(ROOT / "data" / "questions_large.jsonl")}
CONDS = [("rag_v2_k1_gradedv2", "RAG k=1 (weak retrieval)"), ("rag_v2_gradedv2", "RAG k=3"), ("bare_none_gradedv2", "No context")]


def load(path):
    return [json.loads(l) for l in open(path) if l.strip()]


def judged(path):
    """Judge verdicts by question id for one result file, if the judge ran on it."""
    p = Path(path)
    stem = f"{p.parent.name}__{p.stem}" if p.parent.name != "results" else p.stem
    jf = ROOT / "results" / "judge" / f"{stem}.judge.jsonl"
    return {r["id"]: r["judge"] for r in load(jf)} if jf.exists() else {}


def stats(path):
    rows, j = load(path), judged(path)
    changed = [r for r in rows if "changed" in r["tags"]]
    old_values = lambda q: [x for x in q.get("must_not_v2", []) if re.search(r"\d", x)]  # "30 days", not "too late"
    stale = sum(any(x.lower() in r["answer"].lower() for x in old_values(QS[r["id"]])) for r in changed)
    tag = lambda t: (sum(r["pass"] for r in rows if t in r["tags"]), sum(t in r["tags"] for r in rows))
    return {"score": sum(r["pass"] for r in rows), "n": len(rows),
            "judge_score": sum((j[r["id"]] == "correct") if r["id"] in j else r["pass"] for r in rows),
            "stale": stale, "changed_ok": tag("changed")[0], "escalate": tag("escalate"), "silent": tag("silent")}


def lora_runs():
    """{"base": {cond: stats}, "old": [{cond: stats} per seed], "fix": [...]} from the q90 sweep."""
    out = {"base": {}, "old": [], "fix": []}
    for d in sorted(glob.glob(str(ROOT / "results" / "lora" / "q90-*"))):
        kind = "fix" if "-fix-" in d else "old"
        out[kind].append({c: stats(f"{d}/tuned_{c}.jsonl") for c, _ in CONDS})
        if Path(f"{d}/base_{CONDS[0][0]}.jsonl").exists():
            out["base"] = {c: stats(f"{d}/base_{c}.jsonl") for c, _ in CONDS}
    return out


def seeds(runs, cond, key):
    return " / ".join(str(r[cond][key]) for r in runs)


def main():
    lines = ["# Results summary", "", "Generated by `summarize.py` from the files in `results/`. 90 questions, 16 of them changed-policy.", ""]
    lines += ["## DeepSeek V4.1 Flash on serverless (90 questions)", "",
              "| Setup | Keyword score | Judge-adjusted | Changed right | Stale | Escalate | Silent |", "|---|---:|---:|---:|---:|---:|---:|"]
    for name, label in [("bare_v1", "No context, graded v1"), ("stuffed_v1", "Whole policy, v1"), ("rag_v1", "RAG k=3, v1"),
                        ("stuffed_v2", "Whole policy, v2"), ("rag_v2", "RAG k=3, v2"), ("rag_v2_k1", "RAG k=1, v2")]:
        base, _, k = name.partition("_k")
        f = ROOT / "results" / f"{base}_deepseek-v4p1-flash{'_k' + k if k else ''}_q90.jsonl"
        s = stats(f)
        stale = s["stale"] if "v2" in name else "n/a"
        lines.append(f"| {label} | {s['score']}/90 | {s['judge_score']}/90 | {s['changed_ok']}/16 | {stale} | "
                     f"{s['escalate'][0]}/{s['escalate'][1]} | {s['silent'][0]}/{s['silent'][1]} |")
    r = lora_runs()
    lines += ["", "## Muse Glimmer 30B LoRA: old recipe vs fix (graded against v2, 3 shuffle seeds each)", "",
              "Old recipe: 164 examples, no policy in the prompt, so facts go into the weights. Fix: 167 examples, each with",
              "retrieved v1 sections in the prompt (about 1 in 5 a deliberate miss), answers written only from those sections.", ""]
    for c, label in CONDS:
        b = r["base"][c]
        lines += [f"### {label}", "", "| Model | Keyword score | Judge-adjusted | Stale (of 16) | Changed right | Escalate | Silent |",
                  "|---|---:|---:|---:|---:|---:|---:|",
                  f"| Base | {b['score']} | {b['judge_score']} | {b['stale']} | {b['changed_ok']} | {b['escalate'][0]}/11 | {b['silent'][0]}/15 |"]
        for kind, name in [("old", "Old recipe"), ("fix", "Fix")]:
            rs = r[kind]
            esc = " / ".join(str(x[c]["escalate"][0]) for x in rs); sil = " / ".join(str(x[c]["silent"][0]) for x in rs)
            lines.append(f"| {name} (seeds 0 / 1 / 2) | {seeds(rs, c, 'score')} | {seeds(rs, c, 'judge_score')} | "
                         f"{seeds(rs, c, 'stale')} | {seeds(rs, c, 'changed_ok')} | {esc} | {sil} |")
        lines.append("")
    (ROOT / "results" / "SUMMARY.md").write_text("\n".join(lines) + "\n")

    colors = {"Base": "#8c959f", "Old recipe": "#cf222e", "Fix": "#1f6feb"}
    fig, ax = plt.subplots(figsize=(8, 4.2))
    width = 0.26
    for i, (c, label) in enumerate(CONDS):
        for j, (name, vals) in enumerate([("Base", [r["base"][c]["stale"]]), ("Old recipe", [x[c]["stale"] for x in r["old"]]),
                                          ("Fix", [x[c]["stale"] for x in r["fix"]])]):
            xpos = i + (j - 1) * width
            ax.bar(xpos, mean(vals), width * 0.9, color=colors[name], label=name if i == 0 else None)
            ax.text(xpos, max(vals) + 0.3, "/".join(map(str, vals)), ha="center", fontsize=8, color="#24292f")
            if len(vals) > 1: ax.scatter([xpos] * len(vals), vals, color="black", s=12, zorder=3)
    ax.set_xticks(range(len(CONDS)), [l for _, l in CONDS])
    ax.set_ylabel("Stale answers (of 16 changed-policy questions)")
    ax.set_title("After the policy changed, who still gives the old policy?")
    ax.legend(frameon=False); ax.spines[["top", "right"]].set_visible(False)
    fig.text(0.01, 0.01, "Bars: mean of 3 training seeds (dots). Graded against the v2 policy.", fontsize=8, color="#57606a")
    fig.tight_layout(rect=(0, 0.04, 1, 1)); fig.savefig(ROOT / "figures" / "stale_answers.png", dpi=160)

    c = CONDS[0][0]
    fig, ax = plt.subplots(figsize=(6.4, 4))
    ax.axhline(r["base"][c]["score"], color=colors["Base"], ls="--", label=f"Base ({r['base'][c]['score']})")
    for name, kind in [("Old recipe", "old"), ("Fix", "fix")]:
        ax.plot([0, 1, 2], [x[c]["score"] for x in r[kind]], "o-", color=colors[name], label=name)
    ax.set_xticks([0, 1, 2], ["Seed 0", "Seed 1", "Seed 2"]); ax.set_ylabel("Keyword score (of 90)")
    ax.set_title("RAG k=1: the old recipe's lead depends on the seed")
    ax.legend(frameon=False); ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(ROOT / "figures" / "score_by_seed.png", dpi=160)
    print((ROOT / "results" / "SUMMARY.md").read_text())


if __name__ == "__main__":
    main()
